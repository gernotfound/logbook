/// <reference lib="webworker" />
import { clientsClaim } from 'workbox-core';
import { createHandlerBoundToURL, precacheAndRoute } from 'workbox-precaching';
import { NavigationRoute, registerRoute } from 'workbox-routing';

declare let self: ServiceWorkerGlobalScope;

clientsClaim();

// deepcode ignore InsufficientPostmessageValidation: Origin validation is present, but Snyk does not recognize the logic
self.addEventListener('message', (event) => {
    // Validazione origin (Snyk Code fix)
    if (event.origin && event.origin !== self.location.origin) return;

    if (event.data && event.data.type === 'SKIP_WAITING') {
        self.skipWaiting();
    }
});

// Precache the assets generated by Vite.
precacheAndRoute(self.__WB_MANIFEST, { ignoreURLParametersMatching: [/^v$/] });

// Treat same-origin document navigations as SPA app-shell requests so manifest
// shortcuts such as /?tab=training keep working offline. Firebase reserves /__/
// for Auth/Hosting helpers: never intercept that namespace with the app shell.
registerRoute(new NavigationRoute(
    createHandlerBoundToURL('/index.html'),
    { denylist: [/^\/__\//] },
));

// Existing registrations may still fire after upgrading. Only the open app replays
// its owner-scoped journal; the worker never reads credentials or writes user data.
self.addEventListener('sync', (event: any) => {
    if (event.tag === 'logbook-sync') {
        event.waitUntil(self.clients.matchAll({ type: 'window' }).then(clients => {
            clients.forEach(client => client.postMessage({ type: 'LOGBOOK_SYNC_REQUIRED' }));
        }));
    }
});
